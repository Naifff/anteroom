#!/bin/sh
# Резервная копия каталога данных.
#
# Обычный cp живой базы не годится: SQLite в режиме WAL держит часть данных в -wal,
# и копия получится повреждённой ровно тогда, когда понадобится. `.backup` снимает
# согласованный снимок на работающем сервере, останавливать его не нужно.
#
# КОПИЯ СОДЕРЖИТ server.key. Хранить её надо так же, как сам сервер: подмена этого
# ключа позволяет выдавать себя за него при входе.
set -eu

DATA=${DATA:-/var/lib/messenger}
DEST=${DEST:-/var/backup/messenger}/$(date +%F)

mkdir -p "$DEST"

sqlite3 "$DATA/messenger.db" ".backup '$DEST/messenger.db'"

# Блобы копируются отдельно: они лежат на файловой системе, а не в базе, и без них
# восстановленная база ссылается на вложения, которых нет.
if [ -d "$DATA/blobs" ]; then
	cp -a "$DATA/blobs" "$DEST/"
fi

cp -a "$DATA/server.key" "$DEST/"
chmod 600 "$DEST/server.key"

# Копия целиком доступна только владельцу: внутри ключ сервера и шифротексты.
chmod 700 "$DEST"

echo "Копия готова: $DEST"
